def esc(x) -> str:
    return html.escape(str(x), quote=True)


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def read_json(p: Path):
    return json.loads(p.read_text())


def find_registry(reg: dict, repo_name: str, claim: str):
    key = claim.lower()
    hits = [r for r in reg["rasters"] if key in Path(r["path"]).name.lower() and r["path"].lower().endswith((".tif", ".tiff"))]
    same = [r for r in hits if f"{r['owner']}/{r['repo']}" == repo_name]
    pick = (same or hits or [None])[0]
    return pick


def raster_stats(path: Path):
    with rasterio.open(path) as s:
        a = s.read(1)
    finite = np.isfinite(a)
    dots = finite & (a > 0)
    return {"dots": int(dots.sum()), "has_nan": bool((~finite).any()), "min": float(np.nanmin(a)), "max": float(np.nanmax(a)), "shape": list(a.shape)}, a


def build_focus(reg: dict, owner: dict) -> dict:
    rows, arrays = [], {}
    for site in owner["sites"]:
        for claim in site["claims"]:
            hit = find_registry(reg, site["repo"], claim["name"])
            rec = {"site": site["site"], "repo": site["repo"], "pages": site["pages"], "claimed_name": claim["name"],
                   "owner_reported_score": claim["owner_reported_score"], "score_class": "OWNER-REPORTED, UNVERIFIED",
                   "registry_match": None, "registry_sha256": None, "stats": None}
            if hit:
                p = ROOT / hit["local"]
                stats, arr = raster_stats(p)
                rec.update(registry_match=f"{hit['owner']}/{hit['repo']}:{hit['path']}", registry_sha256=hit["sha256"], stats=stats)
                best = max(site["claims"], key=lambda c: c["owner_reported_score"])
                if claim is best:
                    arrays[site["site"]] = arr
            rows.append(rec)
    return {"rows": rows, "best_arrays": arrays}


def focus_overlap(best_arrays: dict) -> dict:
    names = sorted(best_arrays)
    out = {}
    for a in names:
        for b in names:
            if a < b:
                out[f"{a}~{b}"] = round(dot_overlap(best_arrays[a], best_arrays[b]), 4)
    return out


def row_html(r: dict) -> str:
    s = r["stats"] or {}
    match = esc(r["registry_match"] or "NOT FOUND in registry")
    return ("<tr><td>" + esc(r["site"]) + "</td><td><code>" + esc(r["claimed_name"]) + "</code></td>"
            + "<td>" + f"{r['owner_reported_score']:.4f}" + " <small>owner-reported, unverified</small></td>"
            + "<td><small>" + match + "</small></td>"
            + "<td>" + (f"{s.get('dots', 0):,}" if s else "—") + "</td>"
            + "<td><strong>No.</strong> Already a registry submission; a copy would be a duplicate. Learning only.</td>"
            + "<td>No estimate. Not a holdout or organizer score.</td></tr>")


def validator_report(candidate: Path) -> dict:
    return V.validate(TEMPLATE, candidate, "finite-grid", 37_654, allow_zero_outside=None)


