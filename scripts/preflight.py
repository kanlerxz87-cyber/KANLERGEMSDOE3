def operator_receipt_matches(receipt: object, lock: dict) -> bool:
    """Reject stale/contradictory receipts; this is consistency, not authentication.

    A commit label alone does not bind an audit to the exact pinned manifest.
    Missing older receipts must be regenerated by the unmodified-tool audit.
    """
    if not isinstance(receipt, dict) or lock.get("ok") is not True:
        return False
    digest = lock.get("manifest_sha256")
    if not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest):
        return False
    checks = receipt.get("checks")
    return (type(receipt.get("schema_version")) is int
            and receipt["schema_version"] == 1
            and receipt.get("kind") == "SYNTHETIC OPERATOR AUDIT — NOT HOLDOUT-DTI"
            and receipt.get("ok") is True
            and receipt.get("source_lock") == lock
            and receipt.get("blocking_findings") == []
            and isinstance(checks, dict)
            and checks.get("empty_truth_cell_fp_preserved_in_pooled_totals") is True)


def assess(config: dict, root: Path = ROOT, now: datetime | None = None) -> dict:
    failures = []
    resolved = []
    if not isinstance(config, dict):
        return {"research_ready": False, "submit_ready": False, "failures": ["Malformed session configuration"]}
    lane = config.get("assigned_method_paragraph")
    if not isinstance(lane, str) or not lane.strip():
        failures.append("Missing assigned single-method lane paragraph")
    lock = verify_template(root / "vendor" / "shared-template")
    if lock["ok"]:
        resolved.append("Shared evaluator/writer and dependencies restored unmodified and hash-locked")
    else:
        failures.append("Shared template source-lock verification failed")
    receipt_path = root / "data" / "input_receipt.json"
    input_rows = []
    if receipt_path.exists():
        try:
            receipt = json.loads(receipt_path.read_text())
            manifest = json.loads((root / "vendor" / "shared-template" / "registry" / "data_manifest.json").read_text())
            rows = receipt["files"]
            if not isinstance(rows, list) or not rows or not all(isinstance(row, dict) for row in rows):
                raise ValueError("Nonempty object rows required")
            ids = [row["id"] for row in rows]
            if not all(isinstance(key, str) for key in ids) or len(set(ids)) != len(ids):
                raise ValueError("Unique string input IDs required")
            entries = {row["id"]: row for row in manifest["files"]}
            for row in rows:
                canonical = entries.get(row["id"], {})
                if not isinstance(row.get("path"), str) or not row["path"]:
                    raise ValueError("Input path must be a nonempty string")
                path = (root / row["path"]).resolve()
                claimed = row.get("sha256")
                ok = bool(path.is_relative_to(root.resolve()) and path.is_file()
                          and isinstance(claimed, str) and re.fullmatch(r"[0-9a-f]{64}", claimed)
                          and claimed == canonical.get("sha256") and sha256_file(path) == claimed)
                input_rows.append({"id": row["id"], "sha256": claimed, "verified": ok})
            required = {"training_features", "labels", "sample_submission", "ext_derived_sgmc_faults_100m_u8"}
            if required <= {row["id"] for row in input_rows if row["verified"]}:
                resolved.append("Hash-pinned participant-mirror core data restored; data-placement blocker removed")
            else:
                failures.append("Core data absent, corrupt or incomplete")
        except (OSError, ValueError, KeyError, TypeError) as exc:
            # Never retain a partially verified inventory after a malformed receipt.
            input_rows = []
            failures.append("Core data restoration receipt/manifest malformed or unreadable: " + str(exc))
    else:
        failures.append("Core data restoration receipt absent")
    audit_path = root / "evidence" / "shared_tool_audit.json"
    try:
        tool_audit = json.loads(audit_path.read_text()) if audit_path.exists() else {}
    except (OSError, ValueError):
        tool_audit = {}
    if not operator_receipt_matches(tool_audit, lock):
        failures.append("Shared evaluator operator audit fails or is missing; central repair required")
    cache = config.get("shared_cache") if isinstance(config.get("shared_cache"), dict) else {}
    cache_path = (root / cache["path"]).resolve() if isinstance(cache.get("path"), str) and cache["path"] else None
    if not cache_path or not cache_path.is_relative_to(root.resolve()) or not cache_path.is_file() or not isinstance(cache.get("sha256"), str) or sha256_file(cache_path) != cache["sha256"]:
        failures.append("Authenticated shared feature cache/digest not restored; no private rebuild permitted")
    registry = config.get("registry") if isinstance(config.get("registry"), dict) else {}
    if registry.get("complete") is not True:
        failures.append("Complete raster/surface registry not available")
    if registry.get("reference_dot_definition_verified") is not True:
        failures.append("Registry dot representation/saturation unresolved; no diagnostic or lattice is silently exempt")
    incumbent = config.get("same_evaluator_incumbent")
    incumbent_ok = False
    if isinstance(incumbent, dict):
        score, ci, count = incumbent.get("value"), incumbent.get("ci95"), incumbent.get("withheld_positives")
        incumbent_ok = (isinstance(incumbent.get("evaluator_version"), str) and bool(incumbent["evaluator_version"].strip())
                        and isinstance(incumbent.get("fold_sha256"), str) and bool(re.fullmatch(r"[0-9a-f]{64}", incumbent["fold_sha256"]))
                        and type(count) is int and count > 0 and type(score) in (int, float) and math.isfinite(score)
                        and isinstance(ci, list) and len(ci) == 2 and all(type(x) in (int, float) and math.isfinite(x) for x in ci)
                        and 0 <= ci[0] <= score <= ci[1] <= 1)
    if not incumbent_ok:
        failures.append("Same-evaluator, same-fold incumbent evidence absent or malformed")
    experiments = config.get("geological_experiments")
    ledger_ok = isinstance(experiments, list)
    if not ledger_ok:
        experiments = []
    try:
        started = datetime.fromisoformat(config["session_started_utc"])
        elapsed = ((now or datetime.now(timezone.utc)) - started).total_seconds()
        budget_ok = (ledger_ok and type(config["max_seconds"]) is int and type(config["max_experiments"]) is int and started.utcoffset() is not None and 0 <= elapsed < config["max_seconds"] <= 7200 and len(experiments) < config["max_experiments"] <= 3)
    except (KeyError, TypeError, ValueError):
        budget_ok = False
    if not budget_ok:
        failures.append("Experiment/time budget exhausted or malformed")
    # Authentication and slot accounting are separate from research readiness.
    submission_failures = list(failures)
    if config.get("organizer_template_authenticated") is not True:
        submission_failures.append("Official organizer-template provenance not authenticated")
    submission_failures.extend(["No candidate has beaten the paired HOLDOUT-DTI incumbent", "No unique candidate saved bytes/validator receipt exist", "Separate selector has not authorized a weekly slot"])
    return {"schema_version": 1, "research_ready": not failures, "submit_ready": False, "slot_authorized": False, "experiments_used": len(experiments), "submission_slots_used": 0, "resolved": resolved, "failures": failures, "submission_failures": submission_failures, "template": lock, "input_integrity": input_rows, "input_organizer_authenticated": False, "holdout_dti": None, "leaderboard_estimate": None, "scope": "Automated prerequisites only; not a score, no human raster inspection required."}



def digest(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()

def inspect(data: Path, work: Path, manifest: dict, card: dict) -> dict:
    files = []
    for entry in manifest["files"]:
        path = data / entry["dest"]
        actual = digest(path) if path.is_file() else None
        files.append({"id": entry["id"], "file": str(path), "sha256": actual,
                      "verified_against_owner_mirror": actual == entry["sha256"]})
    stack = work / "feature_stack.npy"
    stack_sha = digest(stack) if stack.is_file() else None
    declared = card.get("feature_cache", {})
    stack_ok = (isinstance(declared, dict) and declared.get("provenance_verified") is True
                and stack_sha is not None and stack_sha == declared.get("sha256"))
    lane = card.get("lane", {})
    lane_ok = (isinstance(lane, dict) and lane.get("explicitly_assigned") is True
               and isinstance(lane.get("assigned_method"), str) and bool(lane["assigned_method"].strip()))
    return {"core": files, "mirror_authentication": "not established from organizer",
            "feature_stack": {"file": str(stack), "present": stack.is_file(),
                              "sha256": stack_sha, "provenance_verified": stack_ok},
            "explicit_method_lane": lane_ok,
            "inputs_cache_lane_present": bool(files) and all(x["verified_against_owner_mirror"] for x in files) and stack_ok and lane_ok,
            "ready_for_experiment": False,
            "note": "Inventory only. Use assess() for full session prerequisites; inventory never authorizes an experiment or slot."}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "config" / "research-session-5c1613da.json",
                        help="Fixed session clock and prerequisites; never reset an earlier clock")
    parser.add_argument("--out", type=Path, default=ROOT / "data" / "preflight-live.json",
                        help="Live local receipt (ignored); the published evidence is a dated snapshot")
    args = parser.parse_args()
    observed = datetime.now(timezone.utc)
    try:
        result = assess(json.loads(args.config.read_text()), now=observed)
        exit_code = 0 if result["research_ready"] else 1
    except Exception as exc:
        result = {"schema_version": 1, "research_ready": False, "submit_ready": False, "slot_authorized": False,
                  "failures": ["Prerequisite audit failed: " + str(exc)]}
        exit_code = 2
    try:
        config_label = str(args.config.resolve().relative_to(ROOT.resolve()))
    except ValueError:
        config_label = str(args.config)
    result = {"observed_utc": observed.isoformat(timespec="seconds"), "config": config_label,
              "snapshot_not_live": args.out.resolve().is_relative_to((ROOT / "evidence").resolve()), **result}
    # Replace even an old successful receipt when the current audit cannot run.
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(result, indent=2, allow_nan=False) + "\n")
    print(json.dumps(result, indent=2))
    return exit_code


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:
        print(json.dumps({"research_ready": False, "submit_ready": False, "error": str(exc)}), file=sys.stderr)
        raise SystemExit(2)
