#!/usr/bin/env python3
"""Render the concurrent CFRP result as a fail-closed research archive."""
from __future__ import annotations

import argparse
from html import escape
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from scripts.audit_cfrp_archive import check_receipt  # noqa: E402
from scripts.build_site import page  # noqa: E402

OUT = ROOT / "docs/cfrp-20261028"
RECEIPT = ROOT / "evidence/session-cfcca804-cfrp-audit.json"
CARD = ROOT / "evidence/cfrp_run_card_20261028.json"


def build(check_only: bool = False) -> None:
    raw_receipt = RECEIPT.read_text()
    receipt = json.loads(raw_receipt)
    check_receipt(receipt)
    card = json.loads(CARD.read_text())
    geom = receipt["geometry"]
    hold = card["holdout_dti"]
    selected = hold["E2_selected_V2_44090_collar2"]
    name = escape(Path(receipt["candidate_file"]).name)
    sha = escape(receipt["candidate_sha256"])
    content = f'''<p class="breadcrumb"><a href="../index.html">← Repository executive desk</a></p>
<div class="page-intro"><p class="eyebrow">CFRP concurrent research archive · 28 October 2026</p>
<h1 class="subtitle-page">No CFRP submission is authorized.</h1>
<p>These bytes were generated by a separate session, not by this review. Its original card and evidence are preserved.</p></div>
<div class="notice"><span class="icon" aria-hidden="true">!</span><div><strong>DO NOT SUBMIT · literal all-registry gate fails</strong>
<p>Our saved-byte audit found {geom['candidate_dots_within_3px_of_lattice']:,} / {geom['candidate_dots']:,} dots ({geom['candidate_dot_overlap_fraction']:.2%}) within 3 pixels of the pinned binary lattice. A separate selector cannot waive this stop. The historic focus-nine-only promotion is superseded by this negative decision.</p></div></div>
<section class="section panel prose"><h2>File identity and format scope</h2>
<p>Historical file: <code>{name}</code><br>SHA-256: <code>{sha}</code>. Its saved values are finite inside the mirrored footprint and in [0,1].
The zero-outside TIFF passes the local <code>finite-grid</code> profile but fails <code>template-mask</code> and <code>masked-finite</code>.
The mirror is not organizer-authenticated. The rejected upload was not supplied; its range-error cause and portal acceptance are unknown.</p>
<p><a href="cfrp-audit.json">Independent saved-byte audit →</a> · <a href="cfrp-literal-gate-20261028.json">Prior literal-gate wrapper →</a> · <a href="run-card.json">Original historical card (contains superseded promotion) →</a></p></section>
<section class="section panel prose"><h2>Historical holdout, not a leaderboard forecast</h2>
<p>The prior card reports <strong>HOLDOUT-DTI {selected['dti']:.6f}</strong>, 95% CI [{selected['ci95'][0]:.6f}, {selected['ci95'][1]:.6f}],
<code>{escape(hold['evaluator_version'])}</code>, {hold['withheld_positive_pixels']:,} withheld positives. This review did not rerun it and has no organizer receipt. No reliable leaderboard estimate or verified candidate is available.</p>
<p>Read the <a href="../index.html#comparison">nine-site executive table</a> and the <a href="../executive-summary.html">conditional submission guide</a>. No weekly slot was selected.</p></section>'''
    md = f'''# CFRP archive — DO NOT SUBMIT

The prior research TIFF `{name}` (SHA-256 `{sha}`) has {geom['candidate_dots_within_3px_of_lattice']:,} / {geom['candidate_dots']:,} dots ({geom['candidate_dot_overlap_fraction']:.2%}) within three pixels of the registered binary lattice. Its prior focus-nine-only promotion is superseded; a selector cannot waive the stop.

The original card reports HOLDOUT-DTI {selected['dti']:.6f}, 95% CI [{selected['ci95'][0]:.6f}, {selected['ci95'][1]:.6f}], `{hold['evaluator_version']}`, {hold['withheld_positive_pixels']:,} withheld positives. This was not rerun here and is not an organizer score or a leaderboard forecast.

The zero-outside TIFF passes local `finite-grid`, but fails `template-mask` and `masked-finite` against the participant-mirror sample. Neither local profile proves portal acceptance or the cause of the previously reported range error. See [the saved-byte audit](cfrp-audit.json), [the unchanged historical card](run-card.json), and [the executive desk](../index.html).
'''
    outputs = {
        OUT / "index.html": page("CFRP archive", content, prefix="../"),
        OUT / "EXECUTIVE_SUMMARY.md": md,
        OUT / "cfrp-audit.json": raw_receipt,
    }
    if check_only:
        stale = [str(path.relative_to(ROOT)) for path, content in outputs.items() if not path.is_file() or path.read_text() != content]
        if stale:
            raise ValueError("Stale CFRP archive files: " + ", ".join(stale))
        return
    OUT.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        path.write_text(content)
    print("Built the fail-closed CFRP research archive; no TIFF was generated.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    build(check_only=parser.parse_args().check)
