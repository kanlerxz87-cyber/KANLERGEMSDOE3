# Catalogue-holdout vs owner values and SGMC-CAL vs owner values (n=9); computed once, shown as text.
def _rho():
    from scipy.stats import spearmanr
    foc = J("evidence/focus9-audit-20261029.json")
    champs = J("registry/focus9_champions.json")["entries"]
    own = {c["site"]: c["score_owner_reported"] for c in champs}
    sg = {v["site"]: v for v in foc["sgmc_offcatalogue_proxy"].values()}
    lk = {}
    for k, v in foc["leaky_holdout_diagnostic"].items():
        lk[k.split("__")[0]] = v["pooled_dti_leaky"]
    sites = sorted(own)
    o = [own[s] for s in sites]
    rc = spearmanr(o, [sg[s]["sgmc_prevalence_calibrated_dti"] for s in sites])
    rl = spearmanr(o, [lk[s] for s in sites])
    return rl.statistic, rc.statistic, rc.pvalue


CAT_RHO, SGMC_RHO, SGMC_P = _rho()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    content = build()
    if args.check:
        if not OUT.is_file() or OUT.read_text() != content:
            raise SystemExit(f"{OUT.relative_to(ROOT)} is stale; run scripts/build_submission_desk.py")
        print("submission desk is current")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
